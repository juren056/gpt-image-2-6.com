import { readFileSync, writeFileSync } from 'node:fs';

const en = JSON.parse(readFileSync('messages/en.json', 'utf8'));
const zh = JSON.parse(readFileSync('messages/zh.json', 'utf8'));
const keys = Object.keys(en)
  .filter((key) => key.startsWith('nano_site.'))
  .sort();
for (const key of keys) {
  if (typeof zh[key] !== 'string')
    throw new Error(`Missing Chinese message: ${key}`);
}
// Literal m[...] accesses allow Paraglide/Vite to retain only this editorial
// cluster. A dynamic lookup of the complete m object pulls every site message.
writeFileSync(
  'src/blocks/nano-site-messages.ts',
  [
    '// Generated by scripts/generate-nano-site-messages.mjs; source: messages/{en,zh}.json.',
    "import { m } from '@/paraglide/messages.js';",
    "type ContentLocale = 'en' | 'zh';",
    'const messages: Record<string, (locale: ContentLocale) => string> = {',
    ...keys.map(
      (key) =>
        `  ${JSON.stringify(key.slice('nano_site.'.length))}: (locale) => m[${JSON.stringify(key)}]({}, {locale}),`
    ),
    '};',
    'export function nanoSiteText(key: string, locale: ContentLocale): string {',
    '  const message = messages[key];',
    '  if (!message) throw new Error(`Missing Nano site copy: ${key}`);',
    '  return message(locale);',
    '}',
    '',
  ].join('\n')
);
console.log(`Generated ${keys.length} explicit editorial message accessors`);

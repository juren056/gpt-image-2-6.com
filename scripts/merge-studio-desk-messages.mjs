for (const file of await readdir('messages'))
  if (file.endsWith('.json')) {
    const isChinese = file === 'zh.json' || file === 'zh-TW.json';
    const data = JSON.parse(await readFile(`messages/${file}`, 'utf8'));
    for (const [key, value] of Object.entries(isChinese ? zh : en))
      data[`studio_desk.${key}`] = value;
    for (const [group, pair] of Object.entries(groups))
      data[`studio_desk.group.${group}`] = pair[isChinese ? 1 : 0];
    tools.forEach((row, index) =>
      ['name', 'stage', 'empty', 'hint'].forEach(
        (key, column) =>
          (data[`studio_desk.T${String(index + 1).padStart(2, '0')}.${key}`] =
            row[column + (isChinese ? 4 : 0)])
      )
    );
    await writeFile(`messages/${file}`, JSON.stringify(data, null, 2) + '\n');
  }

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = new URL('../', import.meta.url);
const scopes = JSON.parse(
  readFileSync(new URL('scripts/dynamic-message-scopes.json', root), 'utf8')
);
const catalog = JSON.parse(
  readFileSync(new URL('messages/en.json', root), 'utf8')
);
const prettierConfig = await resolveConfig(
  fileURLToPath(new URL('../package.json', import.meta.url))
);
const check = process.argv.includes('--check');
const out = new URL('src/core/i18n/lookups/', root);
if (!check) mkdirSync(out, { recursive: true });
for (const [scope, prefixes] of Object.entries(scopes)) {
  const keys = Object.keys(catalog)
    .filter((key) => prefixes.some((prefix) => key.startsWith(prefix)))
    .sort();
  if (!keys.length) throw new Error(`Empty dynamic-message scope: ${scope}`);
  const source = await format(
    `// Generated by scripts/generate-dynamic-message-lookups.mjs; do not edit.\nimport { createMessageLookup } from '@/core/i18n/dynamic';\nimport { m } from '@/paraglide/messages.js';\n\nexport const { messages, tDynamic, hasDynamicMessage } = createMessageLookup({\n${keys.map((key) => `  '${key}': m['${key}'],`).join('\n')}\n});\n`,
    { ...prettierConfig, filepath: 'lookup.ts' }
  );
  const path = new URL(`${scope}.ts`, out);
  if (check) {
    if (readFileSync(path, 'utf8') !== source)
      throw new Error(`Stale registry: ${scope}`);
  } else writeFileSync(path, source);
}
console.log(
  `${check ? 'Verified' : 'Generated'} ${Object.keys(scopes).length} bounded message registries`
);
